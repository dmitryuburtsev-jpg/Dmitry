def k1_level_on(pts, start_level, p):
    """отметка лотка в точке p, лежащей на ломаной pts"""
    acc = 0
    for a, b in zip(pts, pts[1:]):
        seg = hypot(b[0]-a[0], b[1]-a[1])
        if seg_dist(p, a, b) < 1e-6:
            return start_level - I*(acc + hypot(p[0]-a[0], p[1]-a[1]))
        acc += seg
    raise ValueError(p)

def cross_x(pts, x):
    """точка ломаной на вертикали x (первое пересечение)"""
    for a, b in zip(pts, pts[1:]):
        if (a[0]-x)*(b[0]-x) <= 0 and a[0] != b[0]:
            t = (x - a[0])/(b[0]-a[0]); return (x, a[1] + t*(b[1]-a[1]))
    return None

def cross_y(pts, y):
    for a, b in zip(pts, pts[1:]):
        if (a[1]-y)*(b[1]-y) <= 0 and a[1] != b[1]:
            t = (y - a[1])/(b[1]-a[1]); return (a[0] + t*(b[0]-a[0]), y)
    return None

