def build():
    wb = Workbook()
    ws = wb.active
    ws.title = "Смета"
    thin = Side(style="thin", color="999999")
    border = Border(left=thin, right=thin, top=thin, bottom=thin)
    head_fill = PatternFill("solid", fgColor="1F4A3A")
    sec_fill = PatternFill("solid", fgColor="E8F0EC")
    tot_fill = PatternFill("solid", fgColor="FFF3D6")
    money = '#,##0" ₽"'

    ws["A1"] = "Смета на строительство хозблока 6,0 × 2,3 м (по крыше), каркасный, утеплённый, с наполнением"
    ws["A1"].font = Font(bold=True, size=13)
    ws["A2"] = ("Цены ориентировочные: розница Московского региона, сентябрь 2026 г. "
                "Перед закупкой уточнить у поставщиков. Объёмы — по чертежам ХБ-6.0х2.3-АР.")
    ws["A2"].font = Font(italic=True, size=9, color="555555")
    cols = ["№", "Наименование", "Ед.", "Кол-во", "Цена, ₽", "Сумма, ₽"]
    widths = [6, 86, 8, 10, 12, 14]
    r = 4
    for j, (c, w) in enumerate(zip(cols, widths), 1):
        cell = ws.cell(r, j, c)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = head_fill
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = border
        ws.column_dimensions[get_column_letter(j)].width = w
    r += 1
    subtot_cells = {}
    md_rows = []
    totals = {}
    for sname, items in SECTIONS:
        ws.cell(r, 1, sname).font = Font(bold=True)
        for j in range(1, 7):
            ws.cell(r, j).fill = sec_fill
            ws.cell(r, j).border = border
        r += 1
        first = r
        stot = 0
        for k, (name, unit, qty, price) in enumerate(items, 1):
            vals = [f"{sname.split('.')[0]}.{k}", name, unit, qty, price]
            for j, v in enumerate(vals, 1):
                c = ws.cell(r, j, v)
                c.border = border
                if j == 2:
                    c.alignment = Alignment(wrap_text=True)
            ws.cell(r, 5).number_format = '#,##0.0#'
            f = ws.cell(r, 6, f"=D{r}*E{r}")
            f.number_format = money
            f.border = border
            stot += qty * price
            md_rows.append((vals[0], name, unit, qty, price, qty * price))
            r += 1
        c = ws.cell(r, 2, f"Итого по разделу «{sname[3:]}»")
        c.font = Font(bold=True)
        s = ws.cell(r, 6, f"=SUM(F{first}:F{r - 1})")
        s.font = Font(bold=True)
        s.number_format = money
        for j in range(1, 7):
            ws.cell(r, j).border = border
        subtot_cells[sname] = f"F{r}"
        totals[sname] = stot
        md_rows.append(("", f"**Итого: {sname[3:]}**", "", "", "", stot))
        r += 2

    mat_secs = [s for s, _ in SECTIONS if not s.startswith("9")]
    lines = [
        ("Материалы (разделы 1–8)", "=" + "+".join(subtot_cells[s] for s in mat_secs)),
        ("   в т.ч. наполнение (раздел 8)", "=" + subtot_cells[SECTIONS[7][0]]),
        ("Работы (раздел 9)", "=" + subtot_cells[SECTIONS[8][0]]),
        ("Итого материалы и работы", None),
        (f"Непредвиденные расходы {int(RESERVE * 100)}%", None),
        ("ВСЕГО ПО СМЕТЕ", None),
    ]
    rows_at = {}
    for name, f in lines:
        rows_at[name] = r
        if name == "Итого материалы и работы":
            f = f"=F{rows_at['Материалы (разделы 1–8)']}+F{rows_at['Работы (раздел 9)']}"
        elif name.startswith("Непредвиденные"):
            f = f"=ROUND(F{rows_at['Итого материалы и работы']}*{RESERVE},0)"
        elif name == "ВСЕГО ПО СМЕТЕ":
            f = f"=F{rows_at['Итого материалы и работы']}+F{r - 1}"
        ws.cell(r, 2, name).font = Font(bold=True, size=12 if name == "ВСЕГО ПО СМЕТЕ" else 11)
        c = ws.cell(r, 6, f)
        c.number_format = money
        c.font = Font(bold=True, size=12 if name == "ВСЕГО ПО СМЕТЕ" else 11)
        for j in range(1, 7):
            ws.cell(r, j).fill = tot_fill
            ws.cell(r, j).border = border
        r += 1
    ws.freeze_panes = "A5"

    # опции
    wo = wb.create_sheet("Опции")
    wo["A1"] = "Дополнительные опции (не входят в итог сметы)"
    wo["A1"].font = Font(bold=True, size=12)
    for j, (c, w) in enumerate(zip(cols, widths), 1):
        cell = wo.cell(3, j, c)
        cell.font = Font(bold=True, color="FFFFFF")
        cell.fill = head_fill
        cell.border = border
        wo.column_dimensions[get_column_letter(j)].width = w
    for k, (name, unit, qty, price) in enumerate(OPTIONS, 1):
        rr = 3 + k
        for j, v in enumerate([f"О.{k}", name, unit, qty, price], 1):
            wo.cell(rr, j, v).border = border
        c = wo.cell(rr, 6, f"=D{rr}*E{rr}")
        c.number_format = money
        c.border = border

    out = ROOT / "smeta" / "smeta_khozblok.xlsx"
    wb.save(out)

    mat = sum(totals[s] for s in mat_secs)
    work = totals[SECTIONS[8][0]]
    sub = mat + work
    res = round(sub * RESERVE)
    grand = sub + res
    return md_rows, totals, mat, work, sub, res, grand


def fmt(v):
    if v == "":
        return ""
    if isinstance(v, float) and not v.is_integer():
        return f"{v:,.1f}".replace(",", " ").replace(".", ",")
    return f"{int(round(v)):,}".replace(",", " ")


def write_md(md_rows, totals, mat, work, sub, res, grand):
    L = ["# Смета: хозблок 6,0 × 2,3 м (по крыше)", "",
         "Каркасный утеплённый хозблок-«распашонка» без перегородок, двускатная кровля, "
         "с наполнением для хранения инструмента, садового инвентаря и техники.", "",
         "> Цены ориентировочные — розница Московского региона, сентябрь 2026 г. "
         "Объёмы посчитаны по чертежам `drawings/khozblok_chertezhi.pdf` "
         "(пиломатериал каркаса — по параметрической модели + 12 % на обрезки). "
         "Excel-версия с формулами: `smeta/smeta_khozblok.xlsx`.", "",
         "## Сводка", "",
         "| Раздел | Сумма, ₽ |", "|---|---:|"]
    for s, v in totals.items():
        L.append(f"| {s} | {fmt(v)} |")
    L += [f"| **Материалы (1–8)** | **{fmt(mat)}** |",
          f"| **Работы (9)** | **{fmt(work)}** |",
          f"| Итого | {fmt(sub)} |",
          f"| Непредвиденные {int(RESERVE * 100)} % | {fmt(res)} |",
          f"| **ВСЕГО** | **{fmt(grand)}** |", "",
          "## Детализация", "",
          "| № | Наименование | Ед. | Кол-во | Цена, ₽ | Сумма, ₽ |", "|---|---|---|---:|---:|---:|"]
    for n, name, unit, qty, price, s in md_rows:
        L.append(f"| {n} | {name} | {unit} | {fmt(qty)} | {fmt(price)} | {fmt(s)} |")
    L += ["", "## Опции (не входят в итог)", "", "| Опция | Сумма, ₽ |", "|---|---:|"]
    for name, unit, qty, price in OPTIONS:
        L.append(f"| {name} | {fmt(qty * price)} |")
    (ROOT / "smeta" / "smeta.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    res = build()
    write_md(*res)
    md_rows, totals, mat, work, sub, r, grand = res
    for s, v in totals.items():
        print(f"{s:60s} {v:>10,.0f}")
    print(f"материалы {mat:,.0f}  работы {work:,.0f}  резерв {r:,.0f}  ВСЕГО {grand:,.0f}")
