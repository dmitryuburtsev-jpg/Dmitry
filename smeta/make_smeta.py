def pcs6(sec, reserve=1.12, length=6.0):
    """Кол-во досок/брусьев длиной 6 м под погонаж модели с запасом."""
    return math.ceil(LUM[sec][1] * reserve / length)


def m3(sec, pcs, length=6.0):
    a, b = map(int, sec.split("x"))
    return round(a * b / 1e6 * length * pcs, 3)


